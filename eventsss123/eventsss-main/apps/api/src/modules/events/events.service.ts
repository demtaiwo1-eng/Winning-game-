import { Prisma } from "@prisma/client";
import { env } from "../../config/env";
import { HttpError } from "../../lib/errors";
import { prisma } from "../../lib/prisma";
import { generateChecklist } from "./checklist.templates";
import type { CreateEventInput, UpdateEventInput } from "./events.schemas";

const REQUIRED_PLAN_ANSWER_KEYS = [
  "desiredOutcome",
  "audienceNeeds",
  "accessibility",
  "dietaryNeeds",
  "programDetails",
  "safetyAndPermits",
  "successMeasures",
] as const;

export const MAX_GUESTS_PER_EVENT = 100_000;

export async function getOwnedEvent(ownerId: string, eventId: string) {
  const ev = await prisma.event.findFirst({ where: { id: eventId, ownerId } });
  if (!ev) throw new HttpError(404, "NOT_FOUND", "Event not found"); // same answer for "not yours"
  return ev;
}

async function assertVenue(venueId?: string | null) {
  if (!venueId) return;
  const v = await prisma.listing.findFirst({ where: { id: venueId, type: "VENUE", status: "ACTIVE" } });
  if (!v) throw new HttpError(400, "INVALID_VENUE", "Venue not found or not active");
}

export async function createEvent(ownerId: string, input: CreateEventInput) {
  const { autoChecklist, budgetMinor, clientRequestId, ...rest } = input as CreateEventInput & {
    budgetMinor?: string | number | null;
  };
  await assertVenue(rest.venueId);
  const budget =
    budgetMinor === undefined || budgetMinor === null || budgetMinor === ""
      ? undefined
      : BigInt(String(budgetMinor));
  if (clientRequestId) {
    const existing = await prisma.event.findFirst({ where: { ownerId, clientRequestId } });
    if (existing) return existing;
  }
  try {
    return await prisma.$transaction(async (tx) => {
      const ev = await tx.event.create({
        data: {
          ...rest,
          currency: rest.currency ?? env.DEFAULT_CURRENCY,
          ownerId,
          ...(clientRequestId ? { clientRequestId } : {}),
          ...(budget !== undefined ? { budgetMinor: budget } : {}),
        } as Prisma.EventUncheckedCreateInput,
      });
      if (autoChecklist) {
        await tx.eventTask.createMany({
          data: generateChecklist(ev.type, ev.startsAt).map((t) => ({ ...t, eventId: ev.id, isAutoGenerated: true })),
        });
      }
      return ev;
    });
  } catch (error) {
    if (
      clientRequestId &&
      error instanceof Prisma.PrismaClientKnownRequestError &&
      error.code === "P2002"
    ) {
      const existing = await prisma.event.findFirst({ where: { ownerId, clientRequestId } });
      if (existing) return existing;
    }
    throw error;
  }
}

export async function listEvents(ownerId: string, q: { status?: string; q?: string; page: number; limit: number }) {
  const where: Prisma.EventWhereInput = {
    ownerId,
    ...(q.status ? { status: q.status as Prisma.EventWhereInput["status"] } : {}),
    ...(q.q ? { title: { contains: q.q, mode: "insensitive" } } : {}),
  };
  const [items, total] = await Promise.all([
    prisma.event.findMany({
      where, orderBy: { createdAt: "desc" }, skip: (q.page - 1) * q.limit, take: q.limit,
      include: { _count: { select: { guests: true, tasks: true } } },
    }),
    prisma.event.count({ where }),
  ]);
  return { items, page: q.page, limit: q.limit, total };
}

export async function getEventDetail(ownerId: string, eventId: string) {
  const event = await getOwnedEvent(ownerId, eventId);
  const [guestGroups, taskGroups, budget] = await Promise.all([
    prisma.guest.groupBy({ by: ["rsvp"], where: { eventId }, _count: true, _sum: { plusOnes: true } }),
    prisma.eventTask.groupBy({ by: ["status"], where: { eventId }, _count: true }),
    prisma.budgetItem.aggregate({ where: { eventId }, _sum: { plannedMinor: true, actualMinor: true } }),
  ]);
  const guests = Object.fromEntries(guestGroups.map((g) => [g.rsvp, g._count]));
  const expectedHeadcount = guestGroups
    .filter((g) => g.rsvp === "ACCEPTED")
    .reduce((n, g) => n + g._count + (g._sum.plusOnes ?? 0), 0);
  return {
    event,
    summary: {
      guests: { byRsvp: guests, expectedHeadcount },
      tasks: Object.fromEntries(taskGroups.map((t) => [t.status, t._count])),
      budget: {
        currency: event.currency,
        plannedMinor: (budget._sum.plannedMinor ?? 0n).toString(),
        actualMinor: (budget._sum.actualMinor ?? 0n).toString(),
      },
    },
  };
}

export async function updateEvent(ownerId: string, eventId: string, input: UpdateEventInput) {
  const existing = await getOwnedEvent(ownerId, eventId);
  if (existing.status === "COMPLETED") {
    throw new HttpError(409, "EVENT_COMPLETED", "A completed event cannot be modified");
  }
  if (input.status === "COMPLETED") {
    throw new HttpError(403, "FORBIDDEN", "Only the event's assigned lead verifier can complete it");
  }
  const startsAt = input.startsAt === undefined ? existing.startsAt : input.startsAt;
  const endsAt = input.endsAt === undefined ? existing.endsAt : input.endsAt;
  if (startsAt && endsAt && endsAt < startsAt) throw new HttpError(400, "VALIDATION_ERROR", "endsAt must not be before startsAt");
  if (input.venueId !== undefined) await assertVenue(input.venueId);
  // null clears optional fields; required columns ignore null
  const data: Record<string, unknown> = { ...input };
  for (const k of ["title", "type", "currency", "isPublic", "status"]) if (data[k] === null) delete data[k];
  return prisma.event.update({ where: { id: eventId }, data: data as Prisma.EventUncheckedUpdateInput });
}

export async function getPlanAnswers(ownerId: string, eventId: string) {
  await getOwnedEvent(ownerId, eventId);
  const rows = await prisma.eventPlanAnswer.findMany({ where: { eventId } });
  const answers = Object.fromEntries(rows.map(({ questionKey, answer }) => [questionKey, answer]));
  return {
    answers,
    complete: REQUIRED_PLAN_ANSWER_KEYS.every((key) => typeof answers[key] === "string" && answers[key].trim().length > 0),
  };
}

export async function savePlanAnswers(
  ownerId: string,
  eventId: string,
  answers: Record<string, string | undefined>,
) {
  await getOwnedEvent(ownerId, eventId);
  const writes = Object.entries(answers).filter((entry): entry is [string, string] => entry[1] !== undefined);
  if (writes.length) {
    await prisma.$transaction(
      writes.map(([questionKey, answer]) =>
        prisma.eventPlanAnswer.upsert({
          where: { eventId_questionKey: { eventId, questionKey } },
          create: { eventId, questionKey, answer },
          update: { answer },
        }),
      ),
    );
  }
  return getPlanAnswers(ownerId, eventId);
}

export async function deleteEvent(ownerId: string, eventId: string) {
  await getOwnedEvent(ownerId, eventId);
  const paid = await prisma.booking.count({ where: { eventId, status: { in: ["PAID", "CONFIRMED", "FULFILLED"] } } });
  if (paid > 0) throw new HttpError(409, "HAS_BOOKINGS", "Cancel the event instead: it has paid bookings");
  await prisma.event.delete({ where: { id: eventId } });
}
