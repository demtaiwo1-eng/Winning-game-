import { Prisma } from "@prisma/client";
import { HttpError } from "../../lib/errors";
import { prisma } from "../../lib/prisma";
import { generateChecklist } from "./checklist.templates";
import { getOwnedEvent } from "./events.service";

export async function listTasks(ownerId: string, eventId: string) {
  await getOwnedEvent(ownerId, eventId);
  return prisma.eventTask.findMany({ where: { eventId }, orderBy: [{ sortOrder: "asc" }, { dueAt: "asc" }] });
}

export async function createTask(ownerId: string, eventId: string, data: { title: string; dueAt?: Date | null }) {
  await getOwnedEvent(ownerId, eventId);
  const last = await prisma.eventTask.aggregate({ where: { eventId }, _max: { sortOrder: true } });
  return prisma.eventTask.create({ data: { ...data, eventId, sortOrder: (last._max.sortOrder ?? -1) + 1 } });
}

async function ownedTask(ownerId: string, eventId: string, taskId: string) {
  await getOwnedEvent(ownerId, eventId);
  const t = await prisma.eventTask.findFirst({ where: { id: taskId, eventId } });
  if (!t) throw new HttpError(404, "NOT_FOUND", "Task not found");
}

export async function updateTask(ownerId: string, eventId: string, taskId: string, data: Prisma.EventTaskUncheckedUpdateInput) {
  await ownedTask(ownerId, eventId, taskId);
  return prisma.eventTask.update({ where: { id: taskId }, data });
}

export async function deleteTask(ownerId: string, eventId: string, taskId: string) {
  await ownedTask(ownerId, eventId, taskId);
  await prisma.eventTask.delete({ where: { id: taskId } });
}

export async function regenerateChecklist(ownerId: string, eventId: string) {
  const ev = await getOwnedEvent(ownerId, eventId);
  const existing = await prisma.eventTask.count({ where: { eventId, isAutoGenerated: true } });
  if (existing > 0) throw new HttpError(409, "ALREADY_GENERATED", "Checklist already generated for this event");
  const base = await prisma.eventTask.aggregate({ where: { eventId }, _max: { sortOrder: true } });
  const offset = (base._max.sortOrder ?? -1) + 1;
  await prisma.eventTask.createMany({
    data: generateChecklist(ev.type, ev.startsAt).map((t) => ({
      ...t, sortOrder: t.sortOrder + offset, eventId, isAutoGenerated: true,
    })),
  });
  return listTasks(ownerId, eventId);
}
